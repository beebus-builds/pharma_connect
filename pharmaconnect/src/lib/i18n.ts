export type MessageKey = keyof typeof en;
export type Dictionary = Record<MessageKey, string>;

/**
 * Registered dictionaries. English is bundled because it is the default and is
 * needed for first paint; every other locale arrives via a dynamic import and is
 * merged in by `registerDictionary`.
 *
 * Previously both tables lived in this module, which shipped roughly 60 KB of
 * Devanagari to every visitor regardless of the language they were reading in.
 */
const dictionaries: Partial<Record<Locale, Dictionary>> = { en };

/** Merge a lazily-loaded dictionary into the registry. */
export function registerDictionary(locale: Locale, dictionary: Dictionary): void {
  dictionaries[locale] = { ...dictionaries[locale], ...dictionary };
}

/** True once `locale` can be rendered without falling back to English. */
export function hasDictionary(locale: Locale): boolean {
  return Boolean(dictionaries[locale]);
}

/**
 * Load a locale's dictionary on demand.
 *
 * Resolves immediately for English and for anything already registered, which is
 * what lets `LocaleProvider` await it before switching the UI — otherwise a
 * Nepali reader would see a flash of English while the chunk downloaded.
 */
export async function loadLocaleDictionary(locale: Locale): Promise<void> {
  if (locale === "en" || hasDictionary(locale)) return;
  const dictionary = await import("@/lib/i18n.ne");
  registerDictionary(locale, dictionary.default);
}

export function isLocale(value: unknown): value is Locale {
  return typeof value === "string" && (LOCALES as readonly string[]).includes(value);
}

export function parseLocale(value: string | null | undefined): Locale | null {
  if (!value) return null;
  if (isLocale(value)) return value;
  const base = value.toLowerCase().split(/[-_]/)[0];
  return isLocale(base) ? base : null;
}

type Params = Record<string, string | number>;

/** Resolve the `A|B` plural variant for the `count` param, then interpolate. */
function resolvePlural(template: string, count: number | undefined): string {
  if (!template.includes("|")) return template;
  const parts = template.split("|");
  return count === 1 || count === 0 ? parts[0] : parts[parts.length - 1];
}

/** Translate a key. `{placeholders}` are substituted; `A|B` picks by count. */
export function translate(
  locale: Locale,
  key: MessageKey,
  params?: Params
): string {
  const template = dictionaries[locale]?.[key] ?? en[key] ?? key;
  const chosen = resolvePlural(template, params?.count === undefined ? undefined : Number(params.count));
  return Object.entries(params ?? {}).reduce(
    (out, [name, value]) => out.split(`{${name}}`).join(String(value)),
    chosen
  );
}

export function getDictionary(locale: Locale): Record<MessageKey, string> {
  return dictionaries[locale] ?? en;
}
